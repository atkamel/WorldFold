"""Experiment 1: diffusion perception as the belief front-end.

Paired comparison of three front-ends on matched occluded configurations
(EXPERIMENTS.md section 1):

    raw   -- nearest-visible-cell fill (deterministic inpainting floor)
    dpm1  -- single DPM sample
    dpmK  -- circular mean of K DPM samples (the belief)

Usage:
    python -m cloth_angles.experiments.exp1_frontends --config cloth_angles/config.yaml \
        --dpm-checkpoint outputs/cloth_angles/diffusion/dpm_020000.pt \
        --wm-checkpoint outputs/cloth_angles/checkpoints/checkpoint_020000.pt

Units are 40 fresh configurations (seeds 1000-1039; 20 light-occlusion, 20
heavy) generated by running the scripted fold to a random cut-off, so the
fields include folds-in-progress. Every front-end sees the identical
(field, mask) pairs -- paired by construction. Primary response: wrapped MAE
on HIDDEN cells. Secondary: 10-step open-loop world-model MAE seeded from
each front-end's reconstruction. Reports Wilcoxon signed-rank and paired-t
per pair, Bonferroni-corrected (alpha 0.05 / 3), plus per-unit CSV so every
statistic is recomputable.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np
import torch
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent / "mujuco"))

from cloth_angles.data.occlusion import nearest_fill, sample_mask
from cloth_angles.model.checkpoint import ExpectedSchema, load_checkpoint
from cloth_angles.model.diffusion import load_dpm_checkpoint, wrapped_abs_error

SEEDS = list(range(1000, 1040))          # 40 units
STRATUM_OF = {s: ("light" if i < 20 else "heavy") for i, s in enumerate(SEEDS)}
HORIZON = 10                              # downstream open-loop steps
ALPHA = 0.05
N_COMPARISONS = 3                         # raw-vs-dpm1, raw-vs-dpmK, dpm1-vs-dpmK


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True)
    parser.add_argument("--dpm-checkpoint", required=True)
    parser.add_argument("--wm-checkpoint", required=True)
    parser.add_argument("--k", type=int, default=8, help="samples in the DPM belief")
    parser.add_argument("--output-dir", default="outputs/cloth_angles/exp1")
    parser.add_argument("--regen-configs", action="store_true",
                         help="regenerate configs.npz even if cached")
    return parser.parse_args()


def load_config(path: str) -> dict:
    with open(path) as f:
        return yaml.safe_load(f)


# ---- unit generation (simulator rollouts; cached to npz) ----

def generate_configs(grid_size: int, path: Path) -> dict:
    """For each seed: reset, run the scripted fold to a random cut-off, record
    the field there, then 10 more (action, next-field) steps for the
    downstream metric. Mask drawn per-unit from the seed's stratum."""
    from sim_main import ClothFoldEnv, ScriptedFoldPolicy  # noqa: PLC0415
    from cloth_angles.collect_episodes import angle_obs  # noqa: PLC0415

    env = ClothFoldEnv(max_episode_steps=250, observation_mode="state")
    fields, masks, strata = [], [], []
    future_actions, future_fields = [], []

    for seed in SEEDS:
        rng = np.random.default_rng(seed)
        offset = rng.uniform(-0.03, 0.03, size=2)
        env.reset(seed=seed, options={"cloth_pose": offset})
        policy = ScriptedFoldPolicy(env)
        t_stop = int(rng.integers(0, 140))
        for _ in range(t_stop):
            env.step(policy.act())
        field = angle_obs(env, grid_size, signed=True)          # [N*N]

        acts, futs = [], []
        for _ in range(HORIZON):
            action = policy.act()
            env.step(action)
            acts.append(action)
            futs.append(angle_obs(env, grid_size, signed=True))

        stratum = STRATUM_OF[seed]
        mask = sample_mask(grid_size, stratum, rng)
        fields.append(field)
        masks.append(mask.reshape(-1))
        strata.append(stratum)
        future_actions.append(np.stack(acts))
        future_fields.append(np.stack(futs))
        print(f"  unit seed={seed} stratum={stratum} t_stop={t_stop}")

    env.close()
    data = {
        "fields": np.stack(fields).astype(np.float32),
        "masks": np.stack(masks).astype(bool),
        "strata": np.array(strata),
        "seeds": np.array(SEEDS),
        "future_actions": np.stack(future_actions).astype(np.float32),
        "future_fields": np.stack(future_fields).astype(np.float32),
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(path, **data)
    return data


# ---- front-ends ----

def circular_mean(samples_rad: torch.Tensor) -> torch.Tensor:
    """[k, N*N] -> [N*N], the circular mean (correct for wrapped angles)."""
    return torch.atan2(torch.sin(samples_rad).mean(dim=0), torch.cos(samples_rad).mean(dim=0))


def reconstructions(dpm, field: np.ndarray, mask: np.ndarray, k: int, device) -> dict:
    n = dpm.grid_size
    field2d = field.reshape(n, n)
    mask2d = mask.reshape(n, n)
    masked = field.copy()
    masked[mask] = 0.0
    f_t = torch.as_tensor(masked, device=device)
    m_t = torch.as_tensor(mask.astype(np.float32), device=device)
    samples = dpm.sample_k(f_t, m_t, k=k)                        # [k, N*N]
    return {
        "raw": torch.as_tensor(nearest_fill(field2d, mask2d).reshape(-1), device=device),
        "dpm1": samples[0],
        "dpmK": circular_mean(samples),
    }


# ---- statistics ----

def paired_stats(a: np.ndarray, b: np.ndarray) -> dict:
    """Paired tests on per-unit errors (a - b): Wilcoxon signed-rank + paired t."""
    from scipy import stats  # noqa: PLC0415

    diff = a - b
    w = stats.wilcoxon(a, b) if np.any(diff != 0) else None
    t = stats.ttest_rel(a, b)
    return {
        "mean_diff": float(diff.mean()),
        "wilcoxon_p": float(w.pvalue) if w is not None else 1.0,
        "paired_t_p": float(t.pvalue),
        "bonferroni_alpha": ALPHA / N_COMPARISONS,
    }


def main():
    args = parse_args()
    config = load_config(args.config)
    data_cfg = config["data"]
    grid_size = data_cfg["grid_size"]
    n = grid_size
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    configs_path = output_dir / "configs.npz"
    if configs_path.exists() and not args.regen_configs:
        print(f"using cached configs: {configs_path}")
        data = dict(np.load(configs_path, allow_pickle=False))
    else:
        print("generating 40 matched configurations (simulator rollouts)...")
        data = generate_configs(grid_size, configs_path)

    dpm, _ = load_dpm_checkpoint(args.dpm_checkpoint, expected_grid_size=grid_size, device=device)
    expected = ExpectedSchema(grid_size=grid_size, action_dim=data_cfg["action_dim"],
                               angle_unit=data_cfg["angle_unit"],
                               angle_convention=data_cfg["angle_convention"])
    wm, _ = load_checkpoint(args.wm_checkpoint, expected, device=device)
    wm.eval()

    front_ends = ("raw", "dpm1", "dpmK")
    rows = []
    for i in range(len(data["seeds"])):
        field = data["fields"][i]
        mask = data["masks"][i]
        stratum = str(data["strata"][i])
        recon = reconstructions(dpm, field, mask, args.k, device)

        true_t = torch.as_tensor(field, device=device)
        mask_t = torch.as_tensor(mask, device=device)
        row = {"seed": int(data["seeds"][i]), "stratum": stratum}
        for fe in front_ends:
            row[f"{fe}_hidden_mae"] = float(
                wrapped_abs_error(recon[fe], true_t)[mask_t].mean()
            )

        # downstream: bootstrap the world model from each reconstruction,
        # imagine HORIZON steps with the recorded actions, compare to truth
        actions_t = torch.as_tensor(data["future_actions"][i], device=device)[None]
        true_future = torch.as_tensor(data["future_fields"][i], device=device).reshape(HORIZON, n, n)
        for fe in front_ends:
            obs0 = recon[fe][None]                                # [1, N*N]
            state = wm.initial_state_from_obs(obs0)
            pred = wm.imagine_angles(state, actions_t, initial_obs=obs0)[0]   # [T, N, N]
            row[f"{fe}_openloop_mae"] = float(wrapped_abs_error(pred, true_future).mean())
        rows.append(row)
        print(f"unit {row['seed']} [{stratum}] " +
              " ".join(f"{fe}={row[f'{fe}_hidden_mae']:.4f}" for fe in front_ends))

    # per-unit CSV (recomputable statistics)
    csv_path = output_dir / "per_unit.csv"
    with open(csv_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    # summary + tests, per stratum and pooled
    results = {"k": args.k, "n_units": len(rows)}
    print("\n=== hidden-cell MAE (rad), mean per arm ===")
    for scope in ("light", "heavy", "all"):
        sel = [r for r in rows if scope == "all" or r["stratum"] == scope]
        arm = {fe: np.array([r[f"{fe}_hidden_mae"] for r in sel]) for fe in front_ends}
        means = {fe: float(arm[fe].mean()) for fe in front_ends}
        results[scope] = {"means": means, "n": len(sel)}
        print(f"[{scope}] n={len(sel)} " + " ".join(f"{fe}={means[fe]:.4f}" for fe in front_ends))
        for pair in (("raw", "dpmK"), ("raw", "dpm1"), ("dpm1", "dpmK")):
            st = paired_stats(arm[pair[0]], arm[pair[1]])
            results[scope][f"{pair[0]}_vs_{pair[1]}"] = st
            sig = "SIG" if st["wilcoxon_p"] < ALPHA / N_COMPARISONS else "ns"
            print(f"    {pair[0]} vs {pair[1]}: mean diff {st['mean_diff']:+.4f}, "
                  f"wilcoxon p={st['wilcoxon_p']:.4g}, t p={st['paired_t_p']:.4g} [{sig}]")

    print("\n=== downstream 10-step open-loop MAE (rad) ===")
    for fe in front_ends:
        vals = np.array([r[f"{fe}_openloop_mae"] for r in rows])
        results.setdefault("openloop", {})[fe] = float(vals.mean())
        print(f"{fe}: {vals.mean():.4f}")

    with open(output_dir / "results.json", "w") as f:
        json.dump(results, f, indent=2)
    print(f"\nwrote {csv_path}")
    print(f"wrote {output_dir / 'results.json'}")


if __name__ == "__main__":
    main()
